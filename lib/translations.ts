export function translateDiagnosis(result: PlantDiagnosisResult, lang: Language): PlantDiagnosisResult {
  if (lang === 'en' || !result) return result;

  if (!result.isCropImage) {
    return {
      ...result,
      crop: TRANSLATION_LABELS[lang].nonPlantWarning,
      issue: TRANSLATION_LABELS[lang].nonPlantWarning,
      explanation: TRANSLATION_LABELS[lang].nonPlantSubtext,
    };
  }

  return result;
}
